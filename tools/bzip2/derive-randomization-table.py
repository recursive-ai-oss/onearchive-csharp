#!/usr/bin/env python3
"""Recovers the bzip2 block-randomisation schedule by black-box experiment and writes it as C#.

bzip2 no longer writes randomised blocks, but its decompressor still reads them: after the inverse
Burrows-Wheeler transform, some bytes are XORed with 1 at positions given by a fixed, cyclic list of
gaps. There is no published copy of that list, so this script measures it:

  1. build a 899000-byte input in which no two neighbouring bytes differ only in the lowest bit and no
     byte repeats (so flipping bit 0 can never form a run for the run-length stage to rewrite);
  2. compress it with `bzip2 -9` (one block), set the "randomised" bit in the block header;
  3. decompress with `bzip2 -dc`. The tool delivers the block's bytes and then reports the CRC error
     that the changed bytes cause; the delivered bytes differ from the input exactly where the
     schedule flips bit 0;
  4. read the gaps between flipped positions. They repeat with period 512; the first flipped position
     and the 512 gaps are the schedule.

Usage: derive-randomization-table.py [path-to-bzip2] > src/OneCompress/BZip2/BZip2RandomizationTable.g.cs
"""
import random
import subprocess
import sys

tool = sys.argv[1] if len(sys.argv) > 1 else "bzip2"
version = subprocess.run([tool, "--help"], capture_output=True, text=True).stderr.splitlines()[0].strip()

rng = random.Random(5)
data = bytearray()
prev = -1
while len(data) < 899000:
    b = rng.randrange(256)
    if prev >= 0 and (b >> 1) == (prev >> 1):
        continue
    data.append(b)
    prev = b

packed = bytearray(subprocess.run([tool, "-9", "-c"], input=bytes(data), capture_output=True, check=True).stdout)
# Stream header (4 bytes), block magic (6), block CRC (4): the next bit, the top bit of byte 14, is the flag.
packed[14] |= 0x80
out = subprocess.run([tool, "-dc"], input=bytes(packed), capture_output=True).stdout

flips = [i for i in range(min(len(data), len(out))) if data[i] != out[i]]
assert all(data[i] ^ out[i] == 1 for i in flips)
gaps = [flips[i + 1] - flips[i] for i in range(len(flips) - 1)]
assert len(gaps) > 1024 and all(gaps[i] == gaps[i + 512] for i in range(len(gaps) - 512)), "schedule is not periodic"
# gaps[k] is the distance from flip k to flip k + 1; the schedule entry for flip k + 1 is gaps[k], and the
# entry for flip 512 (= flip 0 of the next cycle) is gaps[511].
table = [gaps[511]] + gaps[0:511]
first = flips[0]
assert first == table[0] - 2

print("// <auto-generated>")
print("// Produced by tools/bzip2/derive-randomization-table.py from the behaviour of " + version)
print("// by decompressing a block with the randomised flag set. Do not edit.")
print("// </auto-generated>")
print("namespace RecursiveAI.OneCompress.BZip2;")
print()
print("public static partial class BZip2Randomization")
print("{")
print("    private static ReadOnlySpan<ushort> GapData =>")
print("    [")
for i in range(0, 512, 16):
    print("        " + ", ".join(str(v) for v in table[i:i + 16]) + ",")
print("    ];")
print("}")
